"""Region registry (spec § Seam): regions/<id>/region.toml, engine-owned.

A region's conflict config (the dashboard's ConflictConfig) is either
  - regions/<id>/conflict.json, exported from a TypeScript config (the two
    upstream theaters), or
  - the [conflict] table of region.toml (every later region, spec P3), completed
    with DEFAULT_CLIENT / DEFAULT_SERVER and written to TypeScript by `build_ts`
    (src/lib/conflicts/generated.ts), so a new region is one TOML file.

A source id is "<adapter>:<name>" or "<adapter>:<name>#<k>" when several feeds
share a name; grades and owners are keyed by the part before '#'.
"""
import json
import math
import re
import tomllib
from functools import cache
from pathlib import Path

DIR = Path(__file__).resolve().parent.parent / "regions"
TS = DIR.parent / "src" / "lib" / "conflicts" / "generated.ts"
GRADES = "ABCDEF"

# Display fields a TOML region may omit (upstream ClientConfig / ServerConfig).
DEFAULT_CLIENT = {
    "mapZoom": 5, "cities": [], "cityColors": {"default": "#999999"}, "launchSites": [],
    "strikeLocations": {}, "strikeTargets": [], "alertCities": {}, "missileOrigins": [],
    "flightColors": [], "navyColors": {}, "timeZones": [], "sourceColors": {}, "navyOrder": [],
    "maritimeRegions": [], "countryColors": {}, "regionBoxes": [],
    "alertSystemName": "No air-raid feed", "alertStatusTitle": "NO AIR-RAID FEED",
    "hasDroneTracker": False,
}
DEFAULT_SERVER = {
    "strikeQueries": [], "countryAttribution": [], "defaultCountry": "Unknown",
    "conflictQueries": [], "conflictLocations": [], "countryQueries": [],
    "telegramChannels": [], "ships": [], "shipRegions": [], "alertProvider": "none",
}


def complete(r):
    """Full ConflictConfig of a TOML region: defaults, then geometry derived from
    the bounding box (fires and flights boxes; flights radius = half-diagonal)."""
    c = r["conflict"]
    a, b, lo, hi = r["bbox"]
    box = {"latMin": a, "latMax": b, "lonMin": lo, "lonMax": hi}
    lat, lon = c["client"]["mapCenter"]
    half = 111.2 * math.hypot(b - a, (hi - lo) * math.cos(math.radians((a + b) / 2))) / 2
    client = DEFAULT_CLIENT | {"alertFallbackCenter": [lat, lon],
                               "defaultMissileOrigin": [lat, lon],
                               "defaultRegion": r["name"]} | c["client"]
    server = DEFAULT_SERVER | {"firesBBox": box, "flightsBBox": box,
                               "flightsCenter": {"lat": lat, "lon": lon,
                                                 "dist": min(2500, round(half))}} | c["server"]
    return {"key": r["id"], "label": c["label"],
            "theater": c.get("theater", "OSINT COMMAND CENTER // UNCLASSIFIED"),
            "client": client, "server": server}


@cache
def regions():
    """{id: region dict}; region["conflict"] holds the server config plus the
    client tables the engine reads, as in conflict.json."""
    R = {}
    for p in sorted(DIR.glob("*/region.toml")):
        r = tomllib.loads(p.read_text(encoding="utf8"))
        if "conflict" in r:
            c = complete(r)
            r["config"] = c
            r["conflict"] = {"key": c["key"], "label": c["label"], **c["server"],
                             "client": c["client"]}
        else:
            r["conflict"] = json.loads((p.parent / "conflict.json").read_text(encoding="utf8"))
        r.setdefault("owner", {})
        r.setdefault("pir", [])
        r.setdefault("gate", {})
        r.setdefault("link", [])
        R[r["id"]] = r
    return R


def build_ts():
    """Text of src/lib/conflicts/generated.ts: every TOML region's ConflictConfig,
    typed so that tsc checks it against upstream's interface."""
    C = [r["config"] for r in regions().values() if "config" in r]
    return (
        "// Generated by `py -3.14 -m engine regions` from regions/*/region.toml. Do not edit.\n"
        "import type { ConflictConfig, ServerConfig } from './types';\n\n"
        "type Re = { regex: string; flags: string };\n"
        "type RegexKeys = 'newsRelevanceKeywords' | 'polymarketKeywords' | 'polymarketExclude';\n"
        "type Raw = Omit<ConflictConfig, 'server'> & "
        "{ server: Omit<ServerConfig, RegexKeys> & Record<RegexKeys, Re> };\n\n"
        "const re = (r: Re) => new RegExp(r.regex, r.flags);\n\n"
        f"const RAW: Raw[] = {json.dumps(C, ensure_ascii=False, indent=2)};\n\n"
        "export const GENERATED: ConflictConfig[] = RAW.map(c => ({\n"
        "  ...c,\n"
        "  server: {\n"
        "    ...c.server,\n"
        "    newsRelevanceKeywords: re(c.server.newsRelevanceKeywords),\n"
        "    polymarketKeywords: re(c.server.polymarketKeywords),\n"
        "    polymarketExclude: re(c.server.polymarketExclude),\n"
        "  },\n"
        "}));\n")


def key(source_id):
    return source_id.split("#")[0]


def reliability(r, source_id):
    """Admiralty grade A-F; F (cannot be judged) for an ungraded source."""
    return r["reliability"].get(key(source_id), "F")


def owner(r, source_id):
    k = key(source_id)
    return r["owner"].get(k, k.split(":", 1)[1])


def regex(d):
    """JavaScript RegExp {regex, flags} as compiled Python pattern."""
    return re.compile(d["regex"], re.IGNORECASE if "i" in d["flags"] else 0)


def in_bbox(r, lat, lon):
    a, b, c, d = r["bbox"]
    return a <= lat <= b and c <= lon <= d
