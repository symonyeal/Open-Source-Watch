"""Production, stage 6: INTSUM (24 h) and SITREP (6 h) per region (spec P3).

A product is a template filled with computed facts; nothing is generated by a
language model. Wording follows the standards it cites:
  - event credibility in Admiralty words (STANAG 2511): 1 confirmed, 2 probably
    true, 3 possibly true, 4 doubtful, 5 improbable, 6 cannot be judged;
  - a PIR judgement carries a confidence level (ICD 203): high if a supporting
    event is credibility 1-2, moderate if 3, low otherwise.
"""
import hashlib
from datetime import UTC, datetime, timedelta

from engine import store

WORDS = {1: "confirmed", 2: "probably true", 3: "possibly true", 4: "doubtful",
         5: "improbable", 6: "cannot be judged"}
KIND = {"explosions_remote_violence": "strike or explosion", "battles": "fighting",
        "violence_against_civilians": "violence against civilians", "protests": "protest",
        "riots": "riot", "strategic_developments": "strategic development",
        "air_raid_alert": "air-raid alert", "maritime_incident": "maritime incident",
        "airspace_activity": "drone or missile track", "thermal_anomaly": "thermal anomaly"}
PERIOD = {"intsum": 24, "sitrep": 6}


def confidence(best):
    return "high" if best <= 2 else "moderate" if best == 3 else "low"


def report(r, board, sources, kind="intsum", t=None):
    """Product text (Markdown) for region r over the last PERIOD[kind] hours."""
    t = t or datetime.now(UTC)
    h = PERIOD[kind]
    t0 = t - timedelta(hours=h)
    E = store.query("SELECT * FROM event WHERE region = ? AND t_end > ? AND kind <> "
                    "'thermal_anomaly' ORDER BY credibility, len(observation_ids) DESC, t_end "
                    "DESC LIMIT 12", (r["id"], t0))
    ids = [e["observation_ids"][0] for e in E]
    O = {x["id"]: x for x in store.query(
        "SELECT id, text_en, names FROM observation WHERE id IN (SELECT unnest(?))", (ids,))}
    best = {}
    for e in store.query("SELECT kind, min(credibility) c FROM event WHERE region = ? "
                         "AND t_end > ? GROUP BY kind", (r["id"], t0)):
        best[e["kind"]] = e["c"]
    hist = store.query("SELECT indicator, status, t FROM indicator_status WHERE region = ? AND "
                       "t > ? ORDER BY t", (r["id"], t0))
    L = [f"# {kind.upper()}: {r['name']}",
         (f"Period {t0:%Y-%m-%d %H:%M} to {t:%Y-%m-%d %H:%M} UTC. Automated product of "
          "Open-Source-Watch from public sources; every judgement below is mechanical and needs "
          "analyst review."), "", "## Bottom line"]
    for p in board:
        if p["status"] == "answered":
            k = [i for i in p["indicators"] if i["status"] == "triggered"]
            c = min((best.get(i.get("kind"), 6) for i in k), default=6)
            L.append(f"- **{p['pir']}** {p['question']} Indicator threshold met "
                     f"({', '.join(i['id'] for i in k)}); {confidence(c)} confidence.")
        elif p["status"] == "gap":
            L.append(f"- **{p['pir']}** {p['question']} Cannot be assessed: collection gap.")
        else:
            L.append(f"- **{p['pir']}** {p['question']} No indicator at threshold.")
    L += ["", "## Indicators", "", "| PIR | Indicator | Value | Thresholds | Status |",
          "| --- | --- | --- | --- | --- |"]
    for p in board:
        for i in p["indicators"]:
            if i.get("metric") == "transit":
                v = f"{i['count']} transits, z {i['z']}" if i["z"] is not None else "no AIS data"
                th = f"z ≤ {i['watch_z']} / {i['trigger_z']}"
            else:
                v, th = f"{i['count']} in {i['window_h']} h", f"{i['watch']} / {i['trigger']}"
            L.append(f"| {p['pir']} | {i['id']} {i['name']} | {v} | {th} | {i['status']} |")
    changes = [x for k, x in enumerate(hist)
               if k == 0 or (x["indicator"], x["status"]) != (hist[k - 1]["indicator"],
                                                              hist[k - 1]["status"])]
    seen, moved = {}, []
    for x in changes:
        if seen.get(x["indicator"]) not in (None, x["status"]):
            moved.append(f"- {x['t']:%H:%M} {x['indicator']}: {seen[x['indicator']]} → "
                         f"{x['status']}")
        seen[x["indicator"]] = x["status"]
    if moved:
        L += ["", "Status changes in the period:", *moved]
    H = [p for p in board if p["hypotheses"]]
    if H:
        L += ["", "## Competing hypotheses (ACH)"]
        for p in H:
            L.append(f"{p['pir']}, ranked by inconsistent evidence (fewest first):")
            for x in p["hypotheses"]:
                bad = ", ".join(x["inconsistent"]) or "none"
                un = f"; not assessed: {', '.join(x['unassessed'])}" if x["unassessed"] else ""
                L.append(f"- {x['id']} {x['text']}: inconsistent {bad}{un}")
    L += ["", "## Significant events"]
    for e in E:
        o = O.get(e["observation_ids"][0], {})
        place = (o.get("names") or [f"{e['lat']:.2f}, {e['lon']:.2f}"])[0]
        L.append(f"- {e['t_end']:%d %H:%M} {KIND.get(e['kind'], e['kind'])} near {place}: "
                 f"{WORDS[e['credibility']]} ({len(e['observation_ids'])} reports, "
                 f"{e['n_independent']} independent A/B sources). "
                 f"{(o.get('text_en') or '')[:160]}")
    if not E:
        L.append("- None in the period.")
    bad = [s for s in sources if s["health"] != "ok"]
    L += ["", "## Collection",
          f"{len(sources) - len(bad)} of {len(sources)} sources healthy."
          + (f" Not healthy: {', '.join(s['id'] + ' (' + s['health'] + ')' for s in bad)}."
             if bad else "")]
    if r["link"]:
        L += ["", "## Related analysis"] + [f"- [{x['title']}]({x['url']}): {x['note']}"
                                           for x in r["link"]]
    return "\n".join(L) + "\n"


def product(r, kind, text, t=None):
    t = t or datetime.now(UTC)
    return {"id": hashlib.sha256(f"{r['id']}\0{kind}\0{t.isoformat()}".encode()).hexdigest()[:32],
            "region": r["id"], "kind": kind, "t": t, "period_h": PERIOD[kind], "text": text}
