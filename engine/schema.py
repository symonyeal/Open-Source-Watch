"""Tables of the intelligence chain (spec § Data model).

    Source ─< RawReport ─< Observation >─ Event >─< Entity

`source` is not stored: it is the region registry (engine.regions). Every other
table is a Parquet dataset; rows carry their parent ids, so any observation on
the map traces back to the raw report that produced it.
"""
import pyarrow as pa

T = pa.timestamp("us", tz="UTC")
S = pa.string()

SCHEMA = {
    "collection_run": pa.schema([
        ("source_id", S), ("region", S), ("started_at", T), ("status", S),
        ("n_rows", pa.int32()), ("latency_ms", pa.int32()), ("runner", S),
    ]),
    "raw_report": pa.schema([
        ("id", S), ("source_id", S), ("region", S), ("fetched_at", T),
        ("published_at", T), ("url", S), ("payload", S),
    ]),
    "observation": pa.schema([
        ("id", S), ("raw_id", S), ("source_id", S), ("region", S), ("t", T),
        ("lat", pa.float64()), ("lon", pa.float64()), ("geo_precision", S),
        ("kind", S), ("text_en", S), ("lang", S), ("credibility", pa.int8()),
        ("names", pa.list_(S)), ("t_event", T),   # stated event time (process.when), if any
    ]),
    "event": pa.schema([
        ("id", S), ("region", S), ("t_start", T), ("t_end", T),
        ("lat", pa.float64()), ("lon", pa.float64()), ("kind", S),
        ("observation_ids", pa.list_(S)), ("n_independent", pa.int16()),
        ("credibility", pa.int8()),
    ]),
    "entity": pa.schema([
        ("id", S), ("type", S), ("names", pa.list_(S)), ("identifiers", S),
        ("attributes", S),
    ]),
    "indicator_status": pa.schema([
        ("region", S), ("t", T), ("pir", S), ("indicator", S), ("status", S),
        ("count", pa.int32()),
    ]),
    "product": pa.schema([
        ("id", S), ("region", S), ("kind", S), ("t", T), ("period_h", pa.int16()), ("text", S),
    ]),
    "track_point": pa.schema([
        ("entity_id", S), ("region", S), ("t", T), ("lat", pa.float64()),
        ("lon", pa.float64()), ("heading", pa.float64()), ("speed", pa.float64()),
        ("source_id", S),
    ]),
}

# Derived tables: pure functions of raw_report, regenerated by `engine rebuild`.
DERIVED = ("observation", "event", "entity", "track_point")

GEO_PRECISION = ("point", "city", "admin", "country", "none")

# ACLED event types (ACLED Codebook 2023 §2), extended (spec § Event taxonomy).
# `report` is a processed item that no rule classified; fusion ignores it.
KINDS = (
    "battles", "explosions_remote_violence", "violence_against_civilians",
    "protests", "riots", "strategic_developments",
    "air_raid_alert", "maritime_incident", "airspace_activity", "thermal_anomaly",
    "internet_outage", "report",
)
